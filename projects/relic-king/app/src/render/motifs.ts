/** 8×8 스텐실을 비트마스크로 미리 펼친다(렌더 루프에서 문자열을 다시 읽지 않게) */
export const MOTIF_BITS: Record<SiteId, Uint8Array> = Object.fromEntries(
  (Object.keys(SITE_MOTIF) as SiteId[]).map((s) => {
    const bits = new Uint8Array(64);
    SITE_MOTIF[s].rows.forEach((row, y) => {
      for (let x = 0; x < 8; x++) bits[y * 8 + x] = row[x] === "#" ? 1 : 0;
    });
    return [s, bits];
  })
) as Record<SiteId, Uint8Array>;
