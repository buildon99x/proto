import { TIER_MIN_LAYER } from "./balance";
import type { Artifact, PaletteId, Shape, SiteId, Tier } from "./types";

/**
 * 유물 데이터셋 (v0.1: 60점).
 *
 * 티어는 지어낸 등급이 아니라 **현실의 현존 개체 수**다.
 *   T4 유일 = 세상에 하나 / T3 = 한 자릿수 / T2 = 수십 / T1 = 수백~수천 / T0 = 수만 이상
 * 애매하면 더 흔한 쪽으로 내린다. "유일하다"는 주장이 틀리면 게임의 전제가 무너지지만,
 * 흔한 쪽으로 잘못 놓는 건 아무도 다치지 않는다. (notes/artifacts-dataset.md §1)
 *
 * ⚠️ 현존 수량·소장처는 1차 자료 검증 대상이다. eval.md §4 참조.
 */

type Row = [
  id: string,
  name: string,
  era: string,
  origin: string,
  holder: string,
  note: string,
  tier: Tier,
  valueFactor: number,
  shape: Shape,
  palette: PaletteId,
  disputed?: string
];

function build(site: SiteId, rows: Row[]): Artifact[] {
  return rows.map((r, i) => ({
    id: r[0],
    name: r[1],
    era: r[2],
    origin: r[3],
    holder: r[4],
    note: r[5],
    tier: r[6],
    valueFactor: r[7],
    shape: r[8],
    palette: r[9],
    disputed: r[10],
    site,
    minLayer: TIER_MIN_LAYER[r[6]],
    seed: (site.charCodeAt(0) * 7919 + i * 104729) >>> 0
  }));
}

