import { CONDITION_INITIAL_BASE_BY_TIER, TIER_MIN_LAYER } from "./balance";
import { hashFrac } from "./hash";
import type { Artifact, Condition, PaletteId, Shape, SiteId, SourceStatus, Tier } from "./types";

/**
 * 유물 데이터셋 (v0.2 — notes/artifacts-dataset.md, 3단계).
 *
 * 티어는 지어낸 등급이 아니라 **현실의 현존 개체 수**다.
 *   T4 유일 = 세상에 하나 / T3 = 한 자릿수 / T2 = 수십 / T1 = 수백~수천 / T0 = 수만 이상
 * 애매하면 더 흔한 쪽으로 내린다. "유일하다"는 주장이 틀리면 게임의 전제가 무너지지만,
 * 흔한 쪽으로 잘못 놓는 건 아무도 다치지 않는다. (notes/artifacts-dataset.md §1)
 *
 * `sourceStatus: "pending"`인 종은 드랍 풀에서 제외된다(engine.ts candidates()·spawnTip(),
 * notes/artifacts-dataset.md §5, G-B8) — 검증을 마치는 대로 "verified"로 바꾸면 자동
 * 편입된다. 거점당 티어 배분·수집 방침은 notes/decisions.md G53, notes/artifacts-dataset.md
 * §8~9 참조.
 */

type Row = [
  id: string,
  name: string,
  era: string,
  origin: string,
  holder: string,
  note: string,
  tier: Tier,
  valueFactor: number,
  shape: Shape,
  palette: PaletteId,
  source: string[],
  sourceStatus: SourceStatus,
  disputed?: string
];

function initialCondition(id: string, tier: Tier): Condition {
  // notes/artifacts-dataset.md §4 공식 그대로: 티어별 기준값 + 결정론 지터(-1~+1).
  const base = CONDITION_INITIAL_BASE_BY_TIER[tier];
  const jitter = Math.floor(hashFrac(`${id}:condition`) * 3) - 1;
  return Math.min(4, Math.max(0, base + jitter)) as Condition;
}

function build(site: SiteId, rows: Row[]): Artifact[] {
  return rows.map((r, i) => ({
    id: r[0],
    name: r[1],
    era: r[2],
    origin: r[3],
    holder: r[4],
    note: r[5],
    tier: r[6],
    valueFactor: r[7],
    shape: r[8],
    palette: r[9],
    source: r[10],
    sourceStatus: r[11],
    disputed: r[12],
    site,
    minLayer: TIER_MIN_LAYER[r[6]],
    condition: initialCondition(r[0], r[6]),
    seed: (site.charCodeAt(0) * 7919 + i * 104729) >>> 0
  }));
}

