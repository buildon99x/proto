import {readFile,writeFile} from 'node:fs/promises';
const dist=new URL('../dist/',import.meta.url);
const read=name=>readFile(new URL(name,dist),'utf8');
const inlineModule=async name=>(await read(name)).replace(/^import[^\n]*\n/gm,'').replace(/\bexport /g,'');
const dataUri=async (file,mime='image/png')=>`data:${mime};base64,${(await readFile(new URL(file,dist))).toString('base64')}`;
let html=await read('index.html'),css=(await read('style.css')).replace(/^@import[^\n]*\n/,'');
const ART=structuredClone((await import('../src/art.js')).ART);
for(const record of Object.values(ART))record.file=await dataUri(record.file);
const {MOTION_ASSETS,MOTION_AXE_ASSET}=await import('../src/motion.js');
const motionAssets=structuredClone(MOTION_ASSETS),axeAsset=structuredClone(MOTION_AXE_ASSET);
for(const record of Object.values(motionAssets))record.file=await dataUri(record.file);
axeAsset.file=await dataUri(axeAsset.file);
const bank=structuredClone((await import('../src/assets/audio-manifest.js')).AUDIO_BANK);
bank.file=await dataUri(bank.file,'audio/wav');
let motion=await inlineModule('motion.js');
motion=motion.replace(/^const MOTION_ASSETS = .*$/m,`const MOTION_ASSETS = ${JSON.stringify(motionAssets)};`).replace(/^const MOTION_AXE_ASSET = .*$/m,`const MOTION_AXE_ASSET = ${JSON.stringify(axeAsset)};`);
let game=(await inlineModule('game.js')).replace("'assets/motion-warrior-axe.png'",JSON.stringify(axeAsset.file));
const scripts=[await inlineModule('data.js'),await inlineModule('growth.js'),await inlineModule('combat.js'),await inlineModule('encounters.js'),`const ART=${JSON.stringify(ART)};`,motion,`const AUDIO_BANK=${JSON.stringify(bank)};`,await inlineModule('audio.js'),await inlineModule('visual.js'),game].join('\n');
html=html.replace('<link rel="stylesheet" href="style.css">',`<style>${css}</style>`).replace('<script type="module" src="game.js"></script>',`<script type="module">${scripts}</script>`);
await writeFile(new URL('Emberwatch.html',dist),html);
console.log('Created self-contained app/dist/Emberwatch.html with actor, axe and sampled audio assets');
