/**
 * 티어 사다리 — 큐레이션과 점검 도구가 **같은 표**를 읽어야 한다.
 *
 * 전에는 `curate-stages.ts` 와 `course-map/stats.ts` 와 `course-map/extract.ts` 가
 * 각자 목표 공식을 들고 있었고, 큐레이션이 사다리를 옮긴 뒤 점검표의 "편차" 열이 옛
 * 목표를 기준으로 계산돼 멀쩡한 스테이지가 +51ms 벗어난 것처럼 보였다. `extract.ts`
 * 의 사본은 0.7.0 에서야 지워졌는데, 그때까지 코스 지도는 0.5.2 에서 버린 공식
 * (190 − (tier−1)×30)으로 "티어 목표" 를 찍고 있었다. 상수를 나눠 갖지 않는다.
 *
 * 값은 공정성 하한(50ms)을 통과한 후보의 실제 분포에서 잡는다 — 공식이 아니라 표다.
 *
 * ## 0.7.0 에서 다시 읽은 것
 *
 * 섹터가 4개가 되고 채점이 기체 4종 평균으로 바뀌면서 도달 가능 범위가 달라졌다.
 * 900후보 × 4티어 전수(`curate-stages.ts --probe`)에서 읽은 것은 셋이다.
 *
 * **① 최선 여유에 193ms 천장이 있다.** 네 티어 모두 상위 10%가 193 에서 멈춘다.
 * 게이트 통로가 모든 코스에 같은 모양으로 들어가고 코스의 최소 여유를 거기서 자르기
 * 때문이다. 그래서 그전 목표 200 은 **도달 불가**였고 티어 1 의 밴드가 한쪽만 열려
 * 있었다 — 0.5.2 가 티어 4 에서 고친 것과 같은 결함이 티어 1 에 있었던 셈이다.
 *
 * **② 티어 1·2·3 의 도달 가능 범위가 서로 같다.** 관문(지속·드리프트·기체편차)을
 * 통과한 뒤 세 티어 모두 139~181ms 이고 중앙값이 172/171/171 이다. 같은 이유다 —
 * 티어 1~3 에서는 최소 여유를 게이트가 지배하므로(최난 구간 25단위 안팎, 섹터가 아니라
 * 게이트 크기다) 섹터 난이도 램프가 여유에 나타나지 않는다. **티어 4 만 섹터가
 * 지배하고**(최난 구간 370단위) 104~169ms 로 분명히 낮다.
 *
 * **③ 그래서 사다리가 눌렸다.** 실제로 얻어지는 곡선은 **177 / 169 / 142 / 128ms** 이고,
 * 특히 **티어 1 과 2 가 8ms 밖에 안 벌어진다.** 목표를 어디에 두든 그렇다 — 티어 2 의
 * 채택은 목표가 160 이든 163 이든 168~170 에서 멈춘다. 그 아래에 후보가 없어서가 아니라
 * (분포는 139 까지 내려간다) 차별화 제약과 겹치면 남지 않기 때문이다. 이것이 숨겨야 할
 * 수치가 아니라 **섹터를 하나 뺀 값**이다.
 *
 * 그만큼 티어 4 의 정체성이 여유가 아니라 **최난 구간의 지속 길이**에 있다는 0.5.2 의
 * 판단이 중요해졌다 — 아래 `PEAK_RUN_RULE`. 티어 1~3 은 지금 여유가 아니라 유형 구성으로
 * 갈린다.
 *
 * 티어 1~3 을 여유로 더 벌리려면 게이트가 최소 여유를 지배하는 구조를 손대야 한다
 * (통로 조임을 Stage 에도 티어별로 들이거나, 게이트 분할 폭을 티어의 함수로 만들거나).
 * 이 판본의 범위가 아니라 남겨 둔다.
 */
export const TARGET_SLACK_MS: Record<number, number> = { 1: 178, 2: 162, 3: 145, 4: 120 };

export const targetSlackMs = (tier: number): number => TARGET_SLACK_MS[tier] ?? 150;

/**
 * 최난 구간(최선×1.25 이내가 이어지는 길이, 월드 단위)의 티어별 요구.
 *
 * 경계값은 취향이 아니라 측정이다. 후보 분포가 **양극**이라 (900후보 기준 중앙값
 * 23단위 · 상위 10%가 377단위) 140 과 250 사이에는 후보가 거의 없고, 그래서 경계가
 * 예민하지 않다. 섹터가 4개로 줄어도 이 분포는 그대로였다 — 지속은 코스 길이가 아니라
 * 섹터 하나 안의 성질이기 때문이다.
 */
export const PEAK_RUN_RULE: Record<number, (peak: number) => boolean> = {
  1: (p) => p <= 140,
  2: (p) => p <= 140,
  3: (p) => p <= 140,
  4: (p) => p >= 250
};

